// API: Host Environment Health Check & ODBC Driver Detection
app.post("/api/environment-health", async (req, res) => {
  try {
    const { odbcDriver = "{SQL Server Native Client 11.0}" } = req.body;
    const isWindows = process.platform === "win32";
    const requested = (odbcDriver || "").trim();
    const cleanRequested = requested.replace(/^\{+|\}+$/g, "").toLowerCase();

    const detectedDrivers: Array<{ name: string; architecture?: string; isSqlServerDriver: boolean }> = [];
    let registryQueried = false;

    if (isWindows) {
      try {
        const { stdout: stdout64 } = await execAsync('reg query "HKLM\\SOFTWARE\\ODBC\\ODBCINST.INI\\ODBC Drivers" /s', { timeout: 3500 });
        registryQueried = true;
        for (const line of stdout64.split("\n")) {
          const m = line.trim().match(/^(.+?)\s+REG_SZ\s+(Installed|.*)$/i);
          if (m && m[1]) {
            const raw = m[1].trim();
            detectedDrivers.push({
              name: raw.startsWith("{") ? raw : `{${raw}}`,
              architecture: "64-bit (System)",
              isSqlServerDriver: /sql\s*server|native\s*client|msodbcsql/i.test(raw)
            });
          }
        }
      } catch {
        // Ignored if registry access is limited
      }

      try {
        const { stdout: stdout32 } = await execAsync('reg query "HKLM\\SOFTWARE\\WOW6432Node\\ODBC\\ODBCINST.INI\\ODBC Drivers" /s', { timeout: 3500 });
        registryQueried = true;
        for (const line of stdout32.split("\n")) {
          const m = line.trim().match(/^(.+?)\s+REG_SZ\s+(Installed|.*)$/i);
          if (m && m[1]) {
            const raw = m[1].trim();
            detectedDrivers.push({
              name: raw.startsWith("{") ? raw : `{${raw}}`,
              architecture: "32-bit (WOW6432Node)",
              isSqlServerDriver: /sql\s*server|native\s*client|msodbcsql/i.test(raw)
            });
          }
        }
      } catch {
        // Ignored
      }
    } else {
      // Unix/Linux host
      try {
        const { stdout } = await execAsync("odbcinst -q -d", { timeout: 2000 });
        registryQueried = true;
        for (const line of stdout.split("\n")) {
          const raw = line.trim().replace(/^\[+|\]+$/g, "");
          if (raw) {
            detectedDrivers.push({
              name: `{${raw}}`,
              architecture: "Linux (unixODBC)",
              isSqlServerDriver: /sql\s*server|msodbcsql/i.test(raw)
            });
          }
        }
      } catch {
        // odbcinst CLI not present
      }
    }

    // Default driver list for demonstration if in non-Windows container or empty registry
    if (detectedDrivers.length === 0) {
      detectedDrivers.push(
        { name: "{SQL Server Native Client 11.0}", architecture: "64-bit", isSqlServerDriver: true },
        { name: "{ODBC Driver 17 for SQL Server}", architecture: "64-bit", isSqlServerDriver: true },
        { name: "{SQL Server}", architecture: "64-bit", isSqlServerDriver: true },
        { name: "{Microsoft Access Driver (*.mdb, *.accdb)}", architecture: "64-bit", isSqlServerDriver: false }
      );
    }

    // Remove duplicates
    const uniqueDrivers = Array.from(new Map(detectedDrivers.map(d => [d.name.toLowerCase(), d])).values());

    // Check match
    const matchedDriver = uniqueDrivers.find(d => {
      const dClean = d.name.replace(/^\{+|\}+$/g, "").trim().toLowerCase();
      return dClean === cleanRequested || dClean.includes(cleanRequested) || cleanRequested.includes(dClean);
    });

    const driverExists = Boolean(matchedDriver);

    let warningMessage: string | null = null;
    let resolutionSteps: string[] = [];

    if (!driverExists) {
      warningMessage = `CRITICAL ODBC WARNING: The specified driver "${requested}" does not exist in the host machine's ODBC Drivers catalog. When the PHP service executes odbc_connect(), Windows will return: [Microsoft][ODBC Driver Manager] Data source name not found and no default driver specified.`;
      
      resolutionSteps = [
        `Architecture Mismatch: Check if your PHP CLI is 64-bit (x64) or 32-bit (x86). 64-bit PHP cannot load 32-bit ODBC drivers.`,
        `Installed Drivers: Either switch your ODBC Driver String to an installed driver like "${uniqueDrivers[0]?.name || '{ODBC Driver 17 for SQL Server}'}" or install the missing driver on the host.`,
        `Download Official Driver: Install "Microsoft ODBC Driver 17 for SQL Server" or "SQL Server Native Client 11.0 (sqlncli.msi)" from Microsoft.`,
        `Inspect via Windows UI: Press Win+R, type "odbcad32.exe", and verify the "Drivers" tab.`
      ];
    }

    res.json({
      success: true,
      driverExists,
      requestedDriver: requested,
      matchedDriver: matchedDriver || null,
      detectedDrivers: uniqueDrivers,
      hostInfo: {
        platform: isWindows ? `Windows (${os.release()})` : `Linux Container (${os.platform()} ${os.release()})`,
        arch: os.arch(),
        hostname: os.hostname(),
        isWindows,
        registryQueried,
        testedAt: new Date().toLocaleTimeString()
      },
      warningMessage,
      resolutionSteps
    });
  } catch (err: any) {
    res.status(500).json({
      success: false,
      error: err.message || "Failed to execute host environment health check."
    });
  }
});

// API: Simulate incoming WhatsApp webhook POST request to configured PHP daemon / script
app.post("/api/simulate-webhook", async (req, res) => {
  try {
    const {
      scriptPath = "C:\\whatsapp-sync\\daemon.php",
      phpPath = "C:\\php\\php.exe",
      payload,
      headers = {},
      eventType = "message_received"
    } = req.body;

    const startTime = Date.now();

    // Check payload validity
    let parsedPayload: any = null;
    try {
      parsedPayload = typeof payload === 'string' ? JSON.parse(payload) : payload;
    } catch {
      return res.status(400).json({
        success: false,
        statusCode: 400,
        statusText: "Bad Request",
        error: "Malformed JSON payload provided.",
        executionTimeMs: Date.now() - startTime
      });
    }

    if (!parsedPayload) {
      return res.status(400).json({
        success: false,
        statusCode: 400,
        statusText: "Bad Request",
        error: "Payload cannot be empty.",
        executionTimeMs: Date.now() - startTime
      });
    }

    // Extract common WhatsApp/AISensy fields
    const sender = parsedPayload?.entry?.[0]?.changes?.[0]?.value?.contacts?.[0]?.wa_id ||
                   parsedPayload?.from ||
                   parsedPayload?.phone ||
                   parsedPayload?.mobile ||
                   "+919876543210";
    
    const messageId = parsedPayload?.entry?.[0]?.changes?.[0]?.value?.messages?.[0]?.id ||
                      parsedPayload?.messageId ||
                      parsedPayload?.id ||
                      `wamid.HBgL${Date.now()}`;

    const textBody = parsedPayload?.entry?.[0]?.changes?.[0]?.value?.messages?.[0]?.text?.body ||
                     parsedPayload?.text ||
                     parsedPayload?.message ||
                     parsedPayload?.status ||
                     (parsedPayload?.event ? `Event: ${parsedPayload.event}` : "N/A");

    const hotelCode = parsedPayload?.hotelCode ||
                      parsedPayload?.hotel_code ||
                      parsedPayload?.Whatsapp_hotelcode ||
                      headers["X-WhatsApp-HotelCode"] ||
                      "DEFAULT";

    const hasMedia = Boolean(
      parsedPayload?.entry?.[0]?.changes?.[0]?.value?.messages?.[0]?.document ||
      parsedPayload?.media ||
      parsedPayload?.document ||
      parsedPayload?.pdf
    );

    const mediaFilename = parsedPayload?.entry?.[0]?.changes?.[0]?.value?.messages?.[0]?.document?.filename ||
                          parsedPayload?.media?.filename ||
                          (hasMedia ? "invoice_bill.pdf" : null);

    const statusValue = parsedPayload?.entry?.[0]?.changes?.[0]?.value?.statuses?.[0]?.status ||
                        parsedPayload?.status ||
                        "delivered";

    const executionLogs: string[] = [];
    const timestamp = new Date().toLocaleTimeString();
    
    executionLogs.push(`[${timestamp}] [HTTP-INBOUND] Received POST webhook dispatch target: ${scriptPath}`);
    executionLogs.push(`[${timestamp}] [HEADERS] Content-Type: ${headers['Content-Type'] || 'application/json'}, User-Agent: ${headers['User-Agent'] || 'AISensy-Webhook/2.0'}, Signature: VERIFIED_OK`);
    executionLogs.push(`[${timestamp}] [DAEMON-ROUTER] PHP worker (PID: 4820) spawned for event: ${eventType}`);
    executionLogs.push(`[${timestamp}] [PARSER] Hotel Code: [${hotelCode}] | Sender: [${sender}] | Message ID: [${messageId}]`);
    
    if (eventType === 'status_update') {
      executionLogs.push(`[${timestamp}] [STATUS-CALLBACK] Delivery status received: [${statusValue.toUpperCase()}] for message ${messageId}`);
      executionLogs.push(`[${timestamp}] [ODBC-EXEC] UPDATE tbl_Whatsapp_Outgoing SET DeliveryStatus='${statusValue}', UpdatedAt=GETDATE() WHERE MessageId='${messageId}'`);
    } else {
      executionLogs.push(`[${timestamp}] [INBOUND-MSG] Text: "${textBody.length > 40 ? textBody.substring(0, 40) + '...' : textBody}"`);
      if (hasMedia) {
        executionLogs.push(`[${timestamp}] [MEDIA-DISCOVERY] Attachment: ${mediaFilename} -> scheduled for PDF verification & local storage`);
      }
      executionLogs.push(`[${timestamp}] [ODBC-EXEC] INSERT INTO tbl_Whatsapp_Incoming (HotelCode, Sender, MessageId, Content, Status, CreatedAt) VALUES ('${hotelCode}', '${sender}', '${messageId}', '...', 'QUEUED', GETDATE())`);
    }
    
    executionLogs.push(`[${timestamp}] [ODBC-OK] Transaction committed successfully (1 row affected).`);
    executionLogs.push(`[${timestamp}] [HTTP-RESPONSE] Returning 200 OK to webhook source.`);

    const executionTimeMs = Math.max(16, Date.now() - startTime + Math.floor(Math.random() * 20));

    res.json({
      success: true,
      statusCode: 200,
      statusText: "OK",
      executionTimeMs,
      processedData: {
        eventType,
        sender,
        messageId,
        hotelCode,
        textBody,
        hasMedia,
        mediaFilename,
        deliveryStatus: eventType === 'status_update' ? statusValue : undefined,
        timestamp: new Date().toISOString()
      },
      logs: executionLogs,
      responseBody: {
        status: "success",
        acknowledged: true,
        messageId,
        processedAt: new Date().toISOString(),
        daemon: {
          script: scriptPath,
          php: phpPath,
          status: "PROCESSED_OK"
        }
      }
    });
  } catch (err: any) {
    res.status(500).json({
      success: false,
      statusCode: 500,
      statusText: "Internal Server Error",
      error: err.message || "Failed to process webhook POST"
    });
  }
});

async function startServer() {
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`WhatsApp Windows Service Generator running on http://localhost:${PORT}`);
  });
}

startServer();
