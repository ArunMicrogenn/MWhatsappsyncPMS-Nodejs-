// API: Test S3 Connection & Write Permissions
app.post("/api/test-s3", async (req, res) => {
  try {
    const { s3Bucket, s3Region, s3AccessKey, s3SecretKey, s3Endpoint } = req.body;
    if (!s3Bucket || !s3Region || !s3AccessKey || !s3SecretKey) {
      return res.status(400).json({ success: false, error: "Missing required S3 credentials." });
    }

    const client = new S3Client({
      region: s3Region,
      endpoint: s3Endpoint || undefined,
      credentials: {
        accessKeyId: s3AccessKey,
        secretAccessKey: s3SecretKey,
      },
    });

    const testKey = `_aisensy_test_upload_${Date.now()}.txt`;

    // 1. Test Write Permission (Dry-run upload)
    await client.send(new PutObjectCommand({
      Bucket: s3Bucket,
      Key: testKey,
      Body: "This is a temporary test file generated by AISensy WhatsApp Sync to verify write permissions.",
      ContentType: "text/plain"
    }));
    
    // 2. Clean up the test file
    await client.send(new DeleteObjectCommand({
      Bucket: s3Bucket,
      Key: testKey
    }));
    
    res.json({ success: true, message: "Successfully verified upload & write permissions!" });
  } catch (err: any) {
    res.json({ success: false, error: err.message || "Failed to verify S3 write permissions." });
  }
});

